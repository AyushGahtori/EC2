# 4. Summarize Content
# ──────────────────────────────────────────────

@tool
def summarize_content(text: str) -> str:
    """
    Summarize a long piece of text into key points.
    Use after web_search or wikipedia_search to distil information.
    Input: raw text content to summarize.
    Output: bullet-point summary of key facts.
    """
    if not text or len(text) < 100:
        return text

    # Split into sentences and pick key ones
    sentences = [s.strip() for s in text.replace("\n", " ").split(".") if len(s.strip()) > 40]
    top = sentences[:8]

    summary = "Key points:\n" + "\n".join(f"• {s}." for s in top)
    return summary


# ──────────────────────────────────────────────
# 5. Format Podcast Structure
# ──────────────────────────────────────────────

@tool
def format_podcast_structure(raw_content: str) -> str:
    """
    Take raw research or notes and format them into a podcast episode structure.
    Input: JSON string with 'title', 'key_points' (list), optional 'guests'.
    Output: Episode breakdown — segments, timing, talking points.
    """
    try:
        data = json.loads(raw_content)
    except Exception:
        data = {"title": "Episode", "key_points": [raw_content]}

    title = data.get("title", "Untitled Episode")
    points = data.get("key_points", [])
    guests = data.get("guests", [])
    episode_num = data.get("episode_number", "")

    guest_line = f"**Guests:** {', '.join(guests)}" if guests else ""
    ep_line = f"Episode #{episode_num} — " if episode_num else ""

    segments = "\n".join(
        f"  **Segment {i+1}** [{3+i*2}–{5+i*2} min] — {pt}"
        for i, pt in enumerate(points[:5])
    )

    return f"""
## 📋 EPISODE STRUCTURE
### {ep_line}{title}
{guest_line}

**Total Runtime:** ~{10 + len(points) * 3} minutes

### Segments:
{segments if segments else "  • Main discussion (10 min)"}

### Flow:
1. Cold Open / Hook (1 min)
2. Host Intro + Context (2 min)
3. Main Content Segments (above)
4. Listener Q&A / Reflection (2 min)
5. Outro + CTA (1 min)

### Producer Notes:
- Record in one sitting for energy consistency
- Add chapter markers at each segment
- Music beds: fade in/out at transitions
""".strip()


