# 6. Memory Read
# ──────────────────────────────────────────────

@tool
def memory_read(session_id: str) -> str:
    """
    Read the conversation history for the current session from memory.
    Use this to recall what was discussed earlier in the conversation.
    Input: session_id string.
    Output: recent conversation history as formatted text.
    """
    import asyncio
    from app.services.memory_service import get_session_history

    try:
        loop = asyncio.get_event_loop()
        history = loop.run_until_complete(get_session_history(session_id))
        if not history:
            return "No conversation history found for this session."
        lines = []
        for m in history[-10:]:  # last 10 messages
            lines.append(f"[{m['role'].upper()}]: {m['content'][:200]}")
        return "\n".join(lines)
    except Exception as exc:
        return f"Memory read failed: {exc}"


@tool
def memory_write(content: str) -> str:
    """
    Write a note or insight to memory for later recall.
    Input: JSON with 'session_id' and 'note'.
    Output: confirmation.
    """
    # This is a lightweight tool — actual session writes happen in routes
    try:
        data = json.loads(content)
        return f"Note saved to memory: {data.get('note', '')[:100]}"
    except Exception:
        return "Note acknowledged."


