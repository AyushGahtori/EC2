# ──────────────────────────────────────────────
# 1. Web Search (DuckDuckGo — no API key needed)
# ──────────────────────────────────────────────

@tool
def web_search(query: str) -> str:
    """
    Search the web for current information about a topic.
    Use this when you need recent news, data, or facts not in your knowledge.
    Input: a search query string.
    Output: top search results as text.
    """
    try:
        from duckduckgo_search import DDGS
        results = []
        with DDGS() as ddgs:
            for r in ddgs.text(query, max_results=4):
                results.append(f"• {r['title']}\n  {r['body']}")
        if not results:
            return "No results found."
        return "\n\n".join(results[:4])
    except Exception as exc:
        logger.warning(f"web_search failed: {exc}")
        return f"Web search temporarily unavailable. Error: {exc}"


# ──────────────────────────────────────────────
# 2. Wikipedia Search
# ──────────────────────────────────────────────

@tool
def wikipedia_search(topic: str) -> str:
    """
    Search Wikipedia for background information on a topic.
    Use for established facts, history, definitions.
    Input: a topic or concept name.
    Output: Wikipedia summary text.
    """
    try:
        import wikipedia
        wikipedia.set_lang("en")
        try:
            summary = wikipedia.summary(topic, sentences=6, auto_suggest=True)
            return summary
        except wikipedia.DisambiguationError as e:
            # Try first option
            summary = wikipedia.summary(e.options[0], sentences=5)
            return f"(Disambiguation — showing '{e.options[0]}')\n\n{summary}"
    except Exception as exc:
        logger.warning(f"wikipedia_search failed: {exc}")
        return f"Wikipedia search unavailable: {exc}"


# ──────────────────────────────────────────────
# 3. Generate Podcast Script
# ──────────────────────────────────────────────

@tool
def generate_podcast_script(topic_and_context: str) -> str:
    """
    Generate a complete podcast script for a given topic.
    Input: JSON string with keys 'topic' and optionally 'context', 'duration_minutes', 'style'.
    Output: Fully formatted podcast script with intro, segments, outro.
    """
    try:
        data = json.loads(topic_and_context)
    except Exception:
        data = {"topic": topic_and_context}

    topic = data.get("topic", "unknown topic")
    duration = data.get("duration_minutes", 15)
    style = data.get("style", "conversational")
    context = data.get("context", "")

    script = f"""
# 🎙️ PODCAST SCRIPT: {topic.upper()}
**Duration:** ~{duration} minutes | **Style:** {style.capitalize()}

---

## 🎬 INTRO (60–90 sec)

**[MUSIC FADES IN — upbeat, curious]**

HOST (ARIA):
"Welcome back to *The Signal*, the show where we cut through the noise and get to what actually matters.
I'm ARIA, and today — we're talking about {topic}.
{"Context: " + context if context else ""}
Whether you're brand new to this or deep in it — by the end of today's episode, you'll see it differently. Let's go."

**[MUSIC FADES OUT]**

---

## 📌 SEGMENT 1 — WHAT IS IT? (3–4 min)

HOST:
"So first — let's set the table. What exactly are we talking about when we say {topic}?
A lot of people use the term loosely, but there's real substance here.
Think of it this way: [analogy or framing].
And what makes it fascinating is [angle 1]."

**[SHORT PAUSE — ambient sound]**

---

## 🔍 SEGMENT 2 — WHY IT MATTERS NOW (4–5 min)

HOST:
"Here's what's changed recently, and why now is the critical moment.
[Trend or data point 1].
[Trend or data point 2].
The people who understand {topic} deeply right now? They're going to have a serious advantage."

---

## 💡 SEGMENT 3 — THE REAL STORY / INSIGHT (4–5 min)

HOST:
"But here's the thing most people miss — [counterintuitive insight].
I've been looking at this from [angle], and what stood out was [finding].
Let me paint a picture for you: [story or example]."

---

## 🎯 OUTRO (60–90 sec)

**[MUSIC FADES BACK IN]**

HOST:
"That's a wrap on today's deep dive into {topic}.
If this resonated — share it with someone who'd find it valuable.
And if you want to go deeper, I'll link resources in the show notes.
Until next time — stay curious, stay signal.
I'm ARIA. See you next episode."

**[MUSIC SWELLS — END]**

---
*Script generated by ARIA Podcast Agent*
"""
    return script.strip()


